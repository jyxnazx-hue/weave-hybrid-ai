import type { Edge, Node } from "@xyflow/react";
import type { CanvasEdgeData } from "../types/weave";

const STOP_WORDS = new Set([
  "system", "systems", "data", "model", "models", "method", "methods",
  "research", "concept", "node", "nodes", "process", "state", "approach",
  "information", "analysis", "results", "paper", "study", "using",
]);

export function normalizeEntity(raw: string): string {
  return raw
    .toLowerCase()
    .replace(/[^\w\s-]/g, "")
    .trim();
}

function getNodeEntities(node: Node): string[] {
  const data = node.data as Record<string, unknown>;
  const entities = Array.isArray(data?.entities) ? (data.entities as string[]) : [];
  return entities
    .map(normalizeEntity)
    .filter((e) => e.length > 2 && !STOP_WORDS.has(e));
}

function getNodeRole(node: Node): string {
  const data = node.data as Record<string, unknown>;
  return typeof data?.role === "string" ? data.role : "";
}

/**
 * Generates cross-boundary auto-threads between a newly added node and existing nodes
 * (works both inside and outside Spatial Frames, capped at top 3 matches).
 */
export function computeAutoThreadsForNode(
  newNode: Node,
  existingNodes: Node[],
  existingEdges: Edge[]
): Edge[] {
  if (newNode.type === "frame") return [];
  const newEntities = new Set(getNodeEntities(newNode));
  if (newEntities.size === 0) return [];

  const newRole = getNodeRole(newNode);
  const scored: { target: Node; shared: string[]; score: number; relation: string }[] = [];

  for (const other of existingNodes) {
    if (other.id === newNode.id || other.type === "frame") continue;

    // Skip if edge already exists
    const alreadyLinked = existingEdges.some(
      (e) =>
        (e.source === newNode.id && e.target === other.id) ||
        (e.source === other.id && e.target === newNode.id)
    );
    if (alreadyLinked) continue;

    const otherEntities = getNodeEntities(other);
    const shared = otherEntities.filter((e) => newEntities.has(e));
    if (shared.length === 0) continue;

    const otherRole = getNodeRole(other);
    const isContradiction =
      newRole === "Contradiction" || otherRole === "Contradiction";

    const relation = isContradiction
      ? `contradicts (${shared[0]})`
      : shared.length > 1
      ? `connects: ${shared.slice(0, 2).join(", ")}`
      : `shares: ${shared[0]}`;

    scored.push({
      target: other,
      shared,
      score: shared.length + (isContradiction ? 0.5 : 0),
      relation,
    });
  }

  return scored
    .sort((a, b) => b.score - a.score)
    .slice(0, 3)
    .map((match) => ({
      id: `edge-${newNode.id}-${match.target.id}`,
      source: newNode.id,
      target: match.target.id,
      type: "smoothstep",
      label: match.relation,
      data: {
        relation: match.relation,
        isAutoGenerated: true,
        strength: match.score,
      } satisfies CanvasEdgeData,
      style: {
        stroke: match.relation.startsWith("contradicts") ? "#141413" : "#A8A297",
        strokeWidth: match.relation.startsWith("contradicts") ? 1.6 : 1.1,
        strokeDasharray: match.relation.startsWith("contradicts") ? "4 3" : undefined,
      },
      labelStyle: {
        fill: "#5C5A55",
        fontSize: 10,
        fontFamily: "JetBrains Mono, monospace",
      },
      labelBgStyle: {
        fill: "#FAF8F3",
        fillOpacity: 0.92,
      },
    }));
}

/**
 * Organizes scattered cards into spatial topic neighborhoods by primary entity,
 * parking unlinked stray notes cleanly to the right side.
 */
export function clusterNodesByTopic(nodes: Node[]): Node[] {
  const frames = nodes.filter((n) => n.type === "frame");
  const cards = nodes.filter((n) => n.type !== "frame");
  if (cards.length === 0) return nodes;

  const groups = new Map<string, Node[]>();
  const unlinked: Node[] = [];

  for (const card of cards) {
    const entities = getNodeEntities(card);
    if (entities.length === 0) {
      unlinked.push(card);
    } else {
      const primary = entities[0];
      const bucket = groups.get(primary) || [];
      bucket.push(card);
      groups.set(primary, bucket);
    }
  }

  // Separate singletons with no matching peers into unlinked
  const multiGroups: [string, Node[]][] = [];
  for (const [topic, bucket] of groups.entries()) {
    if (bucket.length === 1) {
      unlinked.push(bucket[0]);
    } else {
      multiGroups.push([topic, bucket]);
    }
  }

  const updatedPositions = new Map<string, { x: number; y: number }>();
  let clusterCol = 0;

  for (const [, bucket] of multiGroups) {
    const baseX = 120 + clusterCol * 420;
    bucket.forEach((card, idx) => {
      updatedPositions.set(card.id, {
        x: baseX + (idx % 2) * 30,
        y: 120 + idx * 230,
      });
    });
    clusterCol++;
  }

  // Park unlinked / stray notes neatly in a clean column on the right
  const strayBaseX = 120 + Math.max(clusterCol, 1) * 440;
  unlinked.forEach((card, idx) => {
    updatedPositions.set(card.id, {
      x: strayBaseX + (idx % 2) * 340,
      y: 120 + Math.floor(idx / 2) * 230,
    });
  });

  return [
    ...frames,
    ...cards.map((c) => {
      const pos = updatedPositions.get(c.id);
      return pos ? { ...c, position: pos } : c;
    }),
  ];
}