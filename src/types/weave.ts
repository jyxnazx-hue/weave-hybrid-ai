/**
 * Core Data Types for Weave: Hybrid On-Device & Cloud Spatial Research App
 * Milestone 2: Obsidian-Inspired Single Infinite Spatial Canvas + Full-Space Document Editor
 */

export type ConceptRole =
  | "Definition"
  | "Mechanism"
  | "Evidence"
  | "Assumption"
  | "Contradiction";

export type InferenceSource = "ON_DEVICE" | "IN_CLOUD" | "UNKNOWN";

export interface MicroFlowNode {
  id: string;
  label: string;
}

export interface MicroFlowEdge {
  from: string;
  to: string;
  relation: string;
}

export interface JargonGlossaryItem {
  term: string;
  definition: string;
}

export interface WeaveNode {
  id: string;
  rawText: string;
  sourceUrl?: string;
  sourceTitle?: string;
  coreClaim: string;
  role: ConceptRole;
  entities: string[]; // 2 to 4 specific domain entities
  xrayBullets?: string[]; // 3 plain-English bullet points
  xrayGlossary?: JargonGlossaryItem[]; // Inline glossary of key domain terms
  microFlow?: {
    nodes: MicroFlowNode[];
    edges: MicroFlowEdge[];
  };
  inferenceSource: InferenceSource;
  createdAt: number;
}

export interface WeaveBriefResult {
  title: string;
  consensusSummary: string;
  contradictions: string[];
  blindSpotQuestions: string[];
  inferenceSource: InferenceSource;
}

export interface ExtractConceptResult {
  coreClaim: string;
  role: ConceptRole;
  entities: string[];
  inferenceSource: InferenceSource;
}

export interface JargonXRayResult {
  bullets: string[];
  glossary?: JargonGlossaryItem[];
  inferenceSource: InferenceSource;
}

export interface MicroFlowResult {
  nodes: MicroFlowNode[];
  edges: MicroFlowEdge[];
  inferenceSource: InferenceSource;
}

export interface RedactResult {
  redactedText: string;
  replacementsCount: number;
  inferenceSource: InferenceSource;
}

export interface FullDocumentNoteResult {
  title: string;
  markdownContent: string;
  inferenceSource: InferenceSource;
  contributingNodeIds: string[];
}

export type OnDeviceModelStatus =
  | "available"
  | "downloading"
  | "downloadable"
  | "unavailable";

// ==========================================
// Milestone 2 Canvas & Node Data Types
// ==========================================

export type CanvasCardType = "concept" | "note" | "diagram" | "document" | "frame";

export interface ConceptNodeData {
  [key: string]: unknown;
  nodeType: "concept";
  id: string;
  rawText: string;
  sourceUrl?: string;
  sourceTitle?: string;
  coreClaim: string;
  role: ConceptRole;
  entities: string[];
  xrayBullets?: string[];
  xrayGlossary?: JargonGlossaryItem[];
  microFlow?: {
    nodes: MicroFlowNode[];
    edges: MicroFlowEdge[];
  };
  inferenceSource: InferenceSource;
  createdAt: number;
  isRedacted?: boolean;
}

export interface NoteNodeData {
  [key: string]: unknown;
  nodeType: "note";
  id: string;
  title: string;
  content: string;
  entities?: string[];
  createdAt: number;
  updatedAt?: number;
}

export interface DiagramNodeData {
  [key: string]: unknown;
  nodeType: "diagram";
  id: string;
  imageBase64: string;
  mimeType: string;
  coreClaim: string;
  role: ConceptRole;
  entities: string[];
  microFlow?: {
    nodes: MicroFlowNode[];
    edges: MicroFlowEdge[];
  };
  inferenceSource: InferenceSource;
  createdAt: number;
}

export interface DocumentNodeData {
  [key: string]: unknown;
  nodeType: "document";
  id: string;
  title: string;
  markdownContent: string;
  contributingNodeIds: string[];
  contributingNodes?: WeaveNode[];
  inferenceSource: InferenceSource;
  createdAt: number;
  updatedAt: number;
  wordCount?: number;
}

export interface FrameNodeData {
  [key: string]: unknown;
  nodeType: "frame";
  id: string;
  label: string;
  width: number;
  height: number;
  createdAt: number;
}

export interface CanvasEdgeData {
  [key: string]: unknown;
  relation: string;
  isAutoGenerated?: boolean;
  strength?: number;
}

export interface CanvasSnapshot {
  nodes: any[];
  edges: any[];
  viewport?: { x: number; y: number; zoom: number };
  savedAt: number;
}
